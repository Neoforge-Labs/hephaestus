"""What a Vercel build must do: the Node pin that .prototools also carries, the
frozen install, and the static-export serving that /errors/<code> depends on."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def _prototools(name: str) -> str:
    m = re.search(rf'^{name}\s*=\s*"([^"]+)"', (ROOT / ".prototools").read_text(encoding="utf-8"), re.M)
    assert m, f"{name} not pinned in .prototools"
    return m.group(1)


def test_install_command_is_plain_bun_and_stays_frozen() -> None:
    # Exact equality: --frozen-lockfile is the guarantee that a Vercel build
    # resolves what bun.lock records, and nothing else in the config replaces it.
    cfg = json.loads((ROOT / "vercel.json").read_text(encoding="utf-8"))
    assert cfg["installCommand"] == "bun install --frozen-lockfile"
    # Build needs no pin: `next build` runs under Node, pinned by engines.node.
    assert cfg["buildCommand"] == "bun run --cwd docs/site build"


def test_install_command_does_not_wrap_bun_in_bunx() -> None:
    """`bunx bun@<version> install` fails on Vercel, observed, not reasoned.

    The config pinned bun that way to stop Vercel choosing its own version. It
    works locally (warm bunx cache) and fails on Vercel: deployment
    dpl_7no6raS2LpKiHdbVHtX8BF4wuaPW died with `BUILD_ERROR`, the log showing
    bunx resolving bun, "Saved lockfile", then exit 1 -- the fetch touches the
    lockfile the very next command demands be unchanged.

    The pin was also solving a problem Vercel does not have. The same log reads
    `Detected bun.lock generated by bun@1.4.x`, so the build image picks its bun
    from the lockfile. `.prototools` still pins bun for this repo's own tooling;
    Vercel's build takes its version from the lockfile and is held to it by
    --frozen-lockfile, which fails loudly rather than resolving something else.
    """
    cfg = json.loads((ROOT / "vercel.json").read_text(encoding="utf-8"))
    assert "bunx" not in cfg["installCommand"]
    assert (ROOT / "bun.lock").is_file(), "Vercel picks its bun from bun.lock; it must be committed"


def test_engines_node_matches_prototools_major() -> None:
    pkg = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    assert pkg["engines"]["node"] == f"{_prototools('node').split('.')[0]}.x"


def test_vercel_config_serves_clean_urls_from_a_static_export() -> None:
    cfg = json.loads((ROOT / "vercel.json").read_text(encoding="utf-8"))
    assert cfg["cleanUrls"] is True  # documented default is false; /errors/<code> needs it
    assert cfg["framework"] is None
    assert cfg["outputDirectory"] == "docs/site/out"
