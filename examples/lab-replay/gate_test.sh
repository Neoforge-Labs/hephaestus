#!/usr/bin/env bash
# The in-repo replay gate: the lab stream's definition of done (design 11).
#
# Four claims, and nothing here is allowed to pass by checking nothing:
#   1. a fixture experiment records a run;
#   2. the run replays WITH THE NETWORK BLOCKED and matches;
#   3. a perturbed frozen input produces a diff naming the value that moved;
#   4. every lab.gates check refuses a violating fixture AND passes a clean one.
#
# Docker-free on purpose. The five-minute path needs a daemon and so runs where
# one is available; this gate is the thing that has to run on every pull
# request, so it needs uv and nothing else. The network block is therefore
# in-process (experiment.py's block_network), and it is self-tested rather than
# assumed -- see the BLOCK assertion below.
#
# Every claim is one `check` line here rather than an assert inside Python, so a
# failure names the claim that broke. The clean side of each gate is asserted
# too: "fails on the violating fixture" is satisfied by a gate that fails on
# everything, which is as useless as one that fails on nothing.
#
# Set LAB_REPLAY_KEEP=1 to leave the work directory behind for inspection.
set -uo pipefail

cd "$(dirname "$0")"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/lab-replay.XXXXXX")"
LOG="$WORK/logs"
mkdir -p "$LOG"
fails=0

cleanup() {
  if [ "${LAB_REPLAY_KEEP:-}" = 1 ]; then
    echo "work directory kept at $WORK"
  else
    rm -rf "$WORK"
  fi
}
trap cleanup EXIT

check() { # check <claim> <command...>
  local claim="$1"; shift
  if "$@"; then echo "PASS  $claim"; else echo "FAIL  $claim"; fails=$((fails + 1)); fi
}

# One step of the fixture. Its output is saved so the assertions below can read
# it, and echoed indented so a CI log shows what the gate saw. Redirected, never
# piped: `cmd | tee` would hand `check` tee's exit status, which is a false pass.
step() { # step <name>
  local name="$1"
  echo "+ experiment.py $name"
  uv run --quiet python experiment.py "$name" --work "$WORK" >"$LOG/$name.txt" 2>&1
  local rc=$?
  sed 's/^/      /' "$LOG/$name.txt"
  return $rc
}

says() { grep -Eq "$1" "$LOG/$2.txt"; }        # the step reported this

# ... and did not report that. The `-s` is load-bearing and not defensive
# tidying: a bare `! grep` over a log that is missing or empty exits non-zero
# for want of a subject, which `!` turns into a pass. That is this wave's defect
# species exactly -- a check that cannot fail -- and it would be invisible,
# because the two claims below are the only ones phrased as an absence.
silent() { [ -s "$LOG/$2.txt" ] && ! grep -Eq "$1" "$LOG/$2.txt"; }

say() { printf '\n== %s\n' "$1"; }

# --- 1. the fixture freezes its own synthetic input --------------------------
say "the frozen inputs, generated by the fixture"
check "the fixture writes its own synthetic frozen input" step freeze
check "the frozen input is content-hashed" \
  says '^FROZEN baseline points=64 data_hash=sha256:[0-9a-f]{64}$' freeze
check "the perturbed variant is a different frozen input" \
  says '^FROZEN perturbed index=48 delta=0\.75 data_hash=sha256:[0-9a-f]{64} differs=True$' freeze

# --- 2. the run, recorded ----------------------------------------------------
say "the run, and its record"
check "the fixture records a run" step record
check "the record is finished and holds both cells" \
  says '^RECORD run_id=fixture-baseline class=(deterministic|provenance-only) complete=yes rows=2 cells=fit,evaluate$' record
check "the record holds the evaluation metrics it produced" \
  says '^VALUE cell=evaluate key=rmse value=[0-9.e+-]+$' record

# The assertion above accepts either class, which is a claim about the record's
# shape and not about which class it earned. On a CLEAN checkout -- which is
# what CI runs -- 7.3's three conditions all hold, so the run MUST come out
# `deterministic`: accepting `provenance-only` there would let this gate pass
# identically with a lockfile it could not find or a repo path git could not
# read, which is a hole big enough to drive the whole claim through. A dirty
# worktree (a developer running the gate mid-edit) classifies `provenance-only`
# legitimately, so there either class is accepted -- and this check still runs
# and can still fail, rather than quietly skipping itself.
#
# The condition tests two things because an empty `git status --porcelain` means
# either of them: a clean tree, or no git work tree at all. Only the first earns
# `deterministic` -- 7.1 nulls `code_sha` where no commit identifies the code and
# 7.2 then makes the run `provenance-only` -- so testing emptiness alone would
# demand `deterministic` from a run that cannot earn it. This gate is in-repo by
# design (see the header: Docker-free, not checkout-free), and outside a work
# tree most of its other checks fail anyway, so the second state is not a
# supported mode and this costs the gate no strength. The condition simply says
# what it means, rather than reading as "if the tree is dirty" and meaning less.
earned_class() {
  if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1 ||
    [ -n "$(git status --porcelain 2>/dev/null)" ]; then
    says '^RECORD run_id=fixture-baseline class=(deterministic|provenance-only) complete=yes' record
  else
    says '^RECORD run_id=fixture-baseline class=deterministic complete=yes' record
  fi
}
check "a clean checkout earns class=deterministic" earned_class

# --- 3. the replay, with the network blocked ---------------------------------
say "the replay, with the network blocked"
check "the replay step runs" step replay
# Without this, "replayed with the network blocked" is a claim nothing checks:
# a block that silently stopped blocking would leave every other assertion
# below passing. Four paths, because one of them going unblocked is enough.
check "the network block refuses DNS, create_connection, connect and urlopen" \
  says '^BLOCK proved=getaddrinfo,create_connection,socket\.connect,urlopen count=4$' replay
check "the replay matched its record exactly" \
  says '^REPLAY baseline matched=yes differences=0 record_unfinished=no$' replay
check "the matching replay named no position at all" silent '^DIFF baseline ' replay

# --- 4. the perturbed input, and the diff that names what moved --------------
say "the perturbed input, and the diff"
check "the perturbed replay step runs" step perturb
check "the network block was in force for the perturbed replay too" \
  says '^BLOCK proved=getaddrinfo,create_connection,socket\.connect,urlopen count=4$' perturb
check "the perturbed replay diverged from the record" \
  says '^REPLAY perturbed matched=no differences=[1-9][0-9]* record_unfinished=no$' perturb
check "the diff names the frozen input that changed" \
  says '^DIFF perturbed cell=- key=data_hash recorded=.sha256:[0-9a-f]{64}. replayed=.sha256:[0-9a-f]{64}.$' perturb
check "the diff names the metric that moved, with both of its values" \
  says '^DIFF perturbed cell=evaluate key=rmse recorded=[0-9.e+-]+ replayed=[0-9.e+-]+$' perturb
check "the diff names the error that moved too" \
  says '^DIFF perturbed cell=evaluate key=mae recorded=[0-9.e+-]+ replayed=[0-9.e+-]+$' perturb
# The perturbation moved one held-out observation, so the training split and
# everything fitted from it is untouched. A report naming `fit` would mean the
# perturbation leaked, and a diff that named every cell would say nothing about
# which value moved.
check "the diff leaves the cell the perturbation did not reach alone" \
  silent '^DIFF perturbed cell=fit ' perturb
check "the diff is written where a reviewer can read it" \
  test -s "$WORK/reports/perturbed.json"

# --- 5. every lab.gates check, against a violating fixture and a clean one ---
say "the gates"
check "every gate runs" step gates
check "the figures gate flags transcribed metrics and passes drawn ones" \
  says '^GATE figures violating=[1-9][0-9]* clean=0$' gates
check "the records gate flags a record that is not one and passes a record" \
  says '^GATE records violating=[1-9][0-9]* clean=0$' gates
check "the citations gate flags a cited run with no record" \
  says '^GATE citations-missing violating=[1-9][0-9]* clean=0$' gates
check "the citations gate flags a cited run that does not reproduce" \
  says '^GATE citations-replay violating=[1-9][0-9]* clean=0$' gates
check "check_all refuses, naming all three gates" \
  says '^GATE check-all refused=yes code=HEPH-[A-Z]+-[0-9]{3} status=412 violations=[1-9][0-9]* gates=citations,figures,records$' gates
check "the code it refuses with is the registry's integrity-gate failure" \
  says '^GATE check-all title=Integrity gate failed$' gates
check "check_all passes every clean subject" \
  says '^GATE check-all-clean refused=no violations=0$' gates
check "check_all refuses to be pointed at nothing" \
  says '^GATE check-all-nothing refused=yes kind=ValueError$' gates

echo
if [ "$fails" -eq 0 ]; then
  echo "lab-replay gate: PASS"
else
  echo "lab-replay gate: FAIL ($fails)"
  exit 1
fi
